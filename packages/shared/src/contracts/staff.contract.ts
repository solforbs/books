/**
 * Staff (F02 §4, ARCH-01 §8 login change). Requires a selected business.
 * Base path: /api/v1/staff
 *   GET   /staff                       -> StaffListResponse   (owners: all; add_staff: their locations)
 *   POST  /staff                       -> CreateStaffResponse (owner, or add_staff for cashier /
 *                                                              storekeeper at their own locations)
 *   PATCH /staff/:membershipId         -> StaffMemberResponse (OWNER ONLY: role, locations,
 *                                                              permission switches, name)
 *   POST  /staff/:membershipId/switch-off  -> StaffMemberResponse (OWNER ONLY; revokes all sessions)
 *   POST  /staff/:membershipId/switch-on   -> StaffMemberResponse (OWNER ONLY)
 *   POST  /staff/:membershipId/reset-password -> ResetPasswordResponse (owner, or add_staff for a
 *                                                              cashier/storekeeper at their locations)
 *   GET   /staff/:membershipId/logins  -> LoginHistoryResponse (owner)
 *   GET   /me/permissions              -> MyAccessResponse    (any member: role, locations, permissions)
 *
 * Rules:
 * - Login is phone or email + password (no SMS). A new person gets a temporary password,
 *   generated by the server and shown ONCE to whoever created them; mustChangePassword=true.
 * - If the phone/email already belongs to a user (e.g. they work in another business), a new
 *   membership is added and their existing password stays; no temporary password is returned.
 * - The same person can't be added twice to one business (`already_member`).
 * - There is always at least one active owner (`last_owner`). Nobody can change their own
 *   role, switches or switch themselves off (`cannot_change_self`).
 * - Non-owners need at least one location (`location_required`); owners see all locations.
 * - Switching off revokes every session of that person in this business immediately; history
 *   stays (G4). Role/location/switch changes take effect on the next request (M3: the role is
 *   read from the database on every request).
 */
import { z } from "zod";
import { normalizeKenyanPhone } from "../identity/phone";
import { PERMISSIONS } from "../identity/permissions";
import { LANGUAGES, ROLES } from "../identity/roles";

const permissionOverridesSchema = z.partialRecord(z.enum(PERMISSIONS), z.boolean());
const locationIds = z.array(z.string().min(1)).max(50);

export const createStaffRequestSchema = z
  .object({
    name: z.string().trim().min(2).max(100),
    phone: z
      .string()
      .trim()
      .transform((v, ctx) => {
        const phone = normalizeKenyanPhone(v);
        if (!phone) ctx.addIssue({ code: "custom", message: "invalid_phone" });
        return phone ?? v;
      })
      .optional(),
    email: z
      .string()
      .trim()
      .toLowerCase()
      .pipe(z.email({ error: "invalid_email" }).max(254))
      .optional(),
    role: z.enum(ROLES),
    locationIds: locationIds.default([]),
    permissions: permissionOverridesSchema.default({}),
    language: z.enum(LANGUAGES).default("en"),
  })
  .refine((d) => d.phone || d.email, { message: "phone_or_email_required", path: ["phone"] })
  .refine((d) => d.role === "owner" || d.locationIds.length > 0, {
    message: "location_required",
    path: ["locationIds"],
  });
export type CreateStaffRequest = z.input<typeof createStaffRequestSchema>;

export const updateStaffRequestSchema = z
  .object({
    name: z.string().trim().min(2).max(100),
    role: z.enum(ROLES),
    locationIds,
    permissions: permissionOverridesSchema,
  })
  .partial()
  .refine((d) => Object.keys(d).length > 0, { message: "nothing_to_update" });
export type UpdateStaffRequest = z.input<typeof updateStaffRequestSchema>;

export const staffMemberSchema = z.object({
  membershipId: z.string(),
  userId: z.string(),
  name: z.string(),
  phone: z.string().nullable(),
  email: z.string().nullable(),
  role: z.enum(ROLES),
  locationIds: z.array(z.string()),
  /** Only explicit per-person switches; defaults come from ROLE_DEFAULT_PERMISSIONS. */
  permissions: permissionOverridesSchema,
  status: z.enum(["active", "switched_off"]),
  mustChangePassword: z.boolean(),
  lastLoginAt: z.string().nullable(),
  createdAt: z.string(),
});
export type StaffMember = z.infer<typeof staffMemberSchema>;
export const staffMemberResponseSchema = z.object({ member: staffMemberSchema });
export const staffListResponseSchema = z.object({ members: z.array(staffMemberSchema) });
export type StaffMemberResponse = z.infer<typeof staffMemberResponseSchema>;
export type StaffListResponse = z.infer<typeof staffListResponseSchema>;

export const createStaffResponseSchema = staffMemberResponseSchema.extend({
  /** Present only when a NEW user was created. Shown once, never stored in plain text. */
  temporaryPassword: z.string().nullable(),
});
export type CreateStaffResponse = z.infer<typeof createStaffResponseSchema>;

export const resetPasswordResponseSchema = z.object({ temporaryPassword: z.string() });
export type ResetPasswordResponse = z.infer<typeof resetPasswordResponseSchema>;

export const loginHistoryResponseSchema = z.object({
  entries: z.array(
    z.object({
      at: z.string(),
      outcome: z.enum(["success", "failure", "locked"]),
      ip: z.string().nullable(),
      device: z.string().nullable(),
    }),
  ),
});
export type LoginHistoryResponse = z.infer<typeof loginHistoryResponseSchema>;

export const myAccessResponseSchema = z.object({
  role: z.enum(ROLES),
  locationIds: z.array(z.string()),
  /** Effective permissions after role defaults and per-person switches. */
  permissions: z.array(z.enum(PERMISSIONS)),
  /** True when the business has any active staff who are not approvers (G1). */
  approvalsActive: z.boolean(),
});
export type MyAccessResponse = z.infer<typeof myAccessResponseSchema>;

export const STAFF_ERROR_CODES = [
  "already_member",
  "last_owner",
  "cannot_change_self",
  "location_required",
  "member_not_found",
  "forbidden",
] as const;
